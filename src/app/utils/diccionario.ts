/** Palabras sueltas de las medidas ("1 tbsp", "To taste", "2 cups"...). */
const MEDIDAS: [RegExp, string][] = [
  [/\bto taste\b/gi, 'al gusto'],
  [/\btablespoons?\b|\btbsp\b|\btbs\b/gi, 'cda.'],
  [/\bteaspoons?\b|\btsp\b/gi, 'cdta.'],
  [/\bcups?\b/gi, 'taza(s)'],
  [/\bpinch\b/gi, 'pizca'],
  [/\bdash\b/gi, 'chorrito'],
  [/\bslices?\b/gi, 'rodaja(s)'],
  [/\bcloves?\b/gi, 'diente(s)'],
  [/\bpieces?\b/gi, 'trozo(s)'],
  [/\bsprigs?\b/gi, 'ramita(s)'],
  [/\bhandful\b/gi, 'puñado'],
  [/\blarge\b/gi, 'grande'],
  [/\bsmall\b/gi, 'chico'],
  [/\bmedium\b/gi, 'mediano'],
  [/\bchopped\b/gi, 'picado'],
  [/\bsliced\b/gi, 'en rodajas'],
  [/\bdiced\b/gi, 'en cubos'],
  [/\bfinely\b/gi, 'finamente'],
  [/\bwhole\b/gi, 'entero'],
  [/\bpods?\b/gi, 'vaina(s)'],
  [/\bcans?\b/gi, 'lata(s)'],
  [/\band\b/gi, 'y'],
  [/\bor\b/gi, 'o'],
];

export function categoriaEs(texto: string | null | undefined): string {
  return buscar(CATEGORIAS, texto);
}

export function areaEs(texto: string | null | undefined): string {
  return buscar(AREAS, texto);
}

export function ingredienteEs(texto: string | null | undefined): string {
  const clave = (texto ?? '').trim().toLowerCase();
  // Si no está tal cual, se prueba sin la "s" final (plural simple)
  return INGREDIENTES[clave] ?? INGREDIENTES[clave.replace(/s$/, '')] ?? (texto ?? '').trim();
}

export function medidaEs(texto: string | null | undefined): string {
  let resultado = (texto ?? '').trim();
  for (const [patron, reemplazo] of MEDIDAS) {
    resultado = resultado.replace(patron, reemplazo);
  }
  return resultado;
}

function buscar(diccionario: Record<string, string>, texto: string | null | undefined): string {
  const original = (texto ?? '').trim();
  return diccionario[original.toLowerCase()] ?? original;
}